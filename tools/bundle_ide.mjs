#!/usr/bin/env node
// Concatenate the IDE modules for classic-script and file:// compatibility.
// Also bundles the DOOM Balloon page (balloon.html) and snapshots the uvsd/
// sources it reads, so it works from disk too.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function bundle(order, out) {
  const parts = [`// Generated by tools/bundle_ide.mjs from ${order.join(', ')} - do not edit.\n(() => {\n"use strict";\n`];
  for (const rel of order) {
    let src = fs.readFileSync(path.join(root, rel), 'utf8');
    src = src.replace(/^import [^;]+;\n/gm, '');
    src = src.replace(/^export (?=(async )?(function|class|const|let)\b)/gm, '');
    parts.push(`// ---- ${rel}\n${src}\n`);
  }
  parts.push('})();\n');
  fs.writeFileSync(path.join(root, out), parts.join(''));
  console.log(`wrote ${out}`);
}

bundle(['ide/flash/an3155.js', 'ide/flash/dfuse.js', 'ide/flash/stlink.js', 'ide/doom-sim.js', 'ide/browser-build.js', 'ide/c-sim.js', 'ide/example-preview.js', 'ide/source-search.js', 'ide/clock-diagram.js', 'ide/window-manager.js', 'ide/app.js'], 'ide/forge.js');
bundle(['ide/doom-sim.js', 'ide/balloon/protocol.js', 'ide/balloon/system.js', 'ide/balloon/obc-source.js', 'ide/balloon/grc.js', 'ide/balloon/modem.js', 'ide/balloon/app.js'], 'ide/balloon.js');

// The uvsd/ text sources balloon.html reads, and the submodule commits
// recorded in the index. Left unchanged when the submodules aren't checked out.
const UVSD_FILES = [
  'uvsd/repos.json',
  'uvsd/uvsd-doom-obc/Core/Src/main.c', 'uvsd/uvsd-doom-obc/Core/Inc/telemetry_sensors.h',
  'uvsd/uvsd-doom-obc/Core/Inc/FreeRTOSConfig.h', 'uvsd/uvsd-doom-obc/uvsd-doom-obc.ioc',
  'uvsd/uvsd-doom-gnu-radio/DOOMflow.grc', 'uvsd/uvsd-doom-gs/assets/palettes.hex',
];
const missing = UVSD_FILES.filter((rel) => !fs.existsSync(path.join(root, rel)));
if (missing.length) {
  console.log(`kept ide/uvsd-sources.js: not checked out: ${missing.join(', ')} (git submodule update --init)`);
} else {
  const files = Object.fromEntries(UVSD_FILES.map((rel) => [rel, fs.readFileSync(path.join(root, rel), 'utf8').replace(/\r\n/g, '\n')]));
  const pins = {};
  for (const line of execFileSync('git', ['ls-files', '-s', 'uvsd'], { cwd: root, encoding: 'utf8' }).split('\n')) {
    const m = line.match(/^160000 ([0-9a-f]{40}) \d+\tuvsd\/(.+)$/);
    if (m) pins[m[2]] = m[1];
  }
  fs.writeFileSync(path.join(root, 'ide/uvsd-sources.js'),
    `// Generated by tools/bundle_ide.mjs from uvsd/ - do not edit.\nwindow.UVSD_SOURCES=${JSON.stringify({ pins, files })};\n`);
  console.log(`wrote ide/uvsd-sources.js (${UVSD_FILES.length} files, ${Object.keys(pins).length} pinned repositories)`);
}
