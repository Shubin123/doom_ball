#!/usr/bin/env node
// Concatenate the IDE modules for classic-script and file:// compatibility.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const order = ['ide/flash/an3155.js', 'ide/flash/dfuse.js', 'ide/doom-sim.js', 'ide/browser-build.js', 'ide/c-sim.js', 'ide/example-preview.js', 'ide/source-search.js', 'ide/clock-diagram.js', 'ide/window-manager.js', 'ide/app.js'];
const parts = [`// Generated by tools/bundle_ide.mjs from ${order.join(', ')} - do not edit.\n(() => {\n"use strict";\n`];
for (const rel of order) {
  let src = fs.readFileSync(path.join(root, rel), 'utf8');
  src = src.replace(/^import [^;]+;\n/gm, '');
  src = src.replace(/^export (?=(async )?(function|class|const|let)\b)/gm, '');
  parts.push(`// ---- ${rel}\n${src}\n`);
}
parts.push('})();\n');
fs.writeFileSync(path.join(root, 'ide/forge.js'), parts.join(''));
console.log('wrote ide/forge.js');
